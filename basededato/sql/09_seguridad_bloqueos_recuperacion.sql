-- Agrega columnas a usuario para registrar intentos fallidos y bloqueos
-- progresivos, tabla para tokens de recuperación de un solo uso y
-- limitación por IP.
-- =====================================================================

BEGIN;

-- 1. Nuevas columnas en usuario (si no existen)
ALTER TABLE usuario 
    ADD COLUMN IF NOT EXISTS intentos_fallidos INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS bloqueado_hasta TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS bloqueos_consecutivos INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS ultimo_intento_fallido TIMESTAMPTZ;

COMMENT ON COLUMN usuario.intentos_fallidos IS 'Contador de intentos fallidos consecutivos de inicio de sesión.';
COMMENT ON COLUMN usuario.bloqueado_hasta IS 'Momento hasta el cual la cuenta está temporalmente bloqueada.';
COMMENT ON COLUMN usuario.bloqueos_consecutivos IS 'Nivel del bloqueo progresivo (0: ninguno, 1: 5min, 2: 15min, 3: 30min, 4+: 60min).';

-- 2. Tabla para tokens de recuperación de contraseña de un solo uso
CREATE TABLE IF NOT EXISTS token_recuperacion (
    id_recuperacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario      INTEGER NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    token_hash      VARCHAR(64) NOT NULL UNIQUE,
    expira_en       TIMESTAMPTZ NOT NULL,
    usado           BOOLEAN NOT NULL DEFAULT FALSE,
    usado_en        TIMESTAMPTZ,
    ip_solicitud    VARCHAR(45),
    creado_en       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_token_recuperacion_hash ON token_recuperacion(token_hash);
CREATE INDEX IF NOT EXISTS idx_token_recuperacion_usuario ON token_recuperacion(id_usuario);

COMMENT ON TABLE token_recuperacion IS 'Tokens criptográficos temporales de un solo uso para restablecer contraseña.';

-- 3. Tabla para limitación de solicitudes y protección por IP
CREATE TABLE IF NOT EXISTS rate_limit_ip (
    ip              VARCHAR(45) PRIMARY KEY,
    intentos        INTEGER NOT NULL DEFAULT 0,
    bloqueado_hasta TIMESTAMPTZ,
    ultimo_intento  TIMESTAMPTZ NOT NULL DEFAULT now()
);


-- =====================================================================
-- 01 - ESQUEMA (TABLAS)  -  SISTEMA ESCUELA MODELO
-- Motor: PostgreSQL 15+ (local o Supabase/Railway como hosting)
-- Ejecutar en este orden:
--   01_esquema -> 02_funciones -> 03_triggers -> 04_procedimientos
--   -> 05_vistas -> 06_seguridad -> 07_datos_iniciales
--   -> 08_datos_prueba (opcional)
-- =====================================================================
-- La base guarda los DATOS y sus RELACIONES (PK, FK, CHECK, UNIQUE).
-- La lógica de negocio (validaciones, permisos por rol, CRUD) está en
-- el backend FastAPI. Detalle en LEEME.md.
--
-- Cambios principales frente al diseño original:
--   * 3FN: calificacion ya no guarda id_gestion (se obtiene del periodo).
--   * USUARIO guarda password_hash (bcrypt, lo genera el backend).
--   * ROL: solo los 4 roles del sistema (CHECK).
--   * Calificaciones por dimensiones (ser, saber, hacer, decidir,
--     autoevaluacion). La tabla AUTOEVALUACION se reemplaza por la
--     dimension marcada como es_autoevaluacion.
--   * PERSONA -> subclases: ON DELETE RESTRICT (bajas logicas) y
--     ON UPDATE CASCADE en TODAS las FK que apuntan a un CI.
--   * Tablas nuevas: materia_grado (plan de estudios), dimension_evaluacion,
--     calificacion_detalle, arancel, beca, seguimiento_estudiante,
--     comunicado, comunicado_lectura.
--   * SERIAL -> IDENTITY, TIMESTAMP -> TIMESTAMPTZ, ip -> INET.
-- =====================================================================

BEGIN;

-- =====================================================================
-- 1. PERSONA (superclase), ROL y especializaciones
-- =====================================================================

CREATE TABLE rol (
    id_rol      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol  VARCHAR(50) NOT NULL UNIQUE
        CHECK (nombre_rol IN ('administrador', 'profesor', 'estudiante', 'tutor')),
    descripcion_rol VARCHAR(150)
);
COMMENT ON TABLE rol IS 'Los 4 roles fijos del sistema. Los permisos de cada rol los aplica el backend.';

CREATE TABLE persona (
    ci               VARCHAR(20)  PRIMARY KEY,
    expedido         VARCHAR(2)
        CHECK (expedido IN ('LP','CB','SC','OR','PT','CH','TJ','BE','PD')),
    nombre_persona   VARCHAR(100) NOT NULL,
    apellidos        VARCHAR(100) NOT NULL,
    sexo             CHAR(1) CHECK (sexo IN ('M', 'F')),
    fecha_nacimiento DATE,
    direccion        VARCHAR(150),
    telefono         VARCHAR(20),
    email            VARCHAR(100),
    estado_persona   VARCHAR(20)  NOT NULL DEFAULT 'activo'
        CHECK (estado_persona IN ('activo', 'inactivo')),
    creado_en        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_en   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
COMMENT ON COLUMN persona.ci IS 'Numero de documento incluyendo el complemento si lo tiene (ej. 1234567-1B).';
COMMENT ON COLUMN persona.email IS 'Correo de contacto de la persona.';

CREATE TABLE profesor (
    ci_profesor            VARCHAR(20) PRIMARY KEY
        REFERENCES persona(ci) ON UPDATE CASCADE ON DELETE RESTRICT,
    titulo_academico       VARCHAR(100),
    fecha_contrato         DATE,
    antecedentes_laborales TEXT,
    anios_experiencia      INTEGER CHECK (anios_experiencia >= 0)
);

CREATE TABLE estudiante (
    ci_estudiante           VARCHAR(20) PRIMARY KEY
        REFERENCES persona(ci) ON UPDATE CASCADE ON DELETE RESTRICT,
    rude                    VARCHAR(20) UNIQUE,
    observacion_medica      TEXT,
    antecedentes_academicos TEXT
);

CREATE TABLE administrativo (
    ci_administrativo VARCHAR(20) PRIMARY KEY
        REFERENCES persona(ci) ON UPDATE CASCADE ON DELETE RESTRICT,
    cargo             VARCHAR(50)
);

CREATE TABLE tutor (
    ci_tutor  VARCHAR(20) PRIMARY KEY
        REFERENCES persona(ci) ON UPDATE CASCADE ON DELETE RESTRICT,
    ocupacion VARCHAR(50)
);

-- =====================================================================
-- 2. USUARIOS Y AUDITORIA
-- =====================================================================

CREATE TABLE usuario (
    id_usuario     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario VARCHAR(50) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    estado_usuario VARCHAR(20) NOT NULL DEFAULT 'activo'
        CHECK (estado_usuario IN ('activo', 'inactivo', 'bloqueado')),
    ultimo_acceso  TIMESTAMPTZ,
    id_rol_usuario INTEGER NOT NULL REFERENCES rol(id_rol),
    ci_persona     VARCHAR(20) NOT NULL UNIQUE
        REFERENCES persona(ci) ON UPDATE CASCADE ON DELETE RESTRICT,
    creado_en      TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE usuario IS 'Cuenta de acceso de una persona. El backend valida la contraseña y emite el token.';
COMMENT ON COLUMN usuario.password_hash IS 'Hash bcrypt generado por el backend. Nunca se guarda la contraseña en texto.';

CREATE TABLE bitacora (
    id_bitacora         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accion              TEXT NOT NULL,
    operacion           VARCHAR(10),
    tabla_afectada      VARCHAR(50),
    registro_id         TEXT,
    datos_anteriores    JSONB,
    datos_nuevos        JSONB,
    fecha_hora          TIMESTAMPTZ NOT NULL DEFAULT now(),
    ip                  INET,
    modulo              VARCHAR(50),
    id_usuario_bitacora INTEGER
        REFERENCES usuario(id_usuario) ON DELETE SET NULL
);
COMMENT ON COLUMN bitacora.id_usuario_bitacora IS 'NULL = operacion hecha fuera del backend (SQL Editor, scripts de carga).';

-- =====================================================================
-- 3. ESTRUCTURA ACADEMICA
-- =====================================================================

CREATE TABLE nivel_educativo (
    id_nivel     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_nivel VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE grado (
    id_grado                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_grado             VARCHAR(50) NOT NULL,
    orden_grado              SMALLINT NOT NULL CHECK (orden_grado > 0),
    id_nivel_educativo_grado INTEGER NOT NULL REFERENCES nivel_educativo(id_nivel),
    UNIQUE (id_nivel_educativo_grado, nombre_grado),
    UNIQUE (id_nivel_educativo_grado, orden_grado)
);

CREATE TABLE gestion (
    id_gestion             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio                   INTEGER NOT NULL UNIQUE,
    fecha_inicio_g         DATE NOT NULL,
    fecha_final_g          DATE NOT NULL,
    nota_minima_aprobacion NUMERIC(5,2) NOT NULL DEFAULT 51
        CHECK (nota_minima_aprobacion BETWEEN 0 AND 100),
    estado_gestion         VARCHAR(20) NOT NULL DEFAULT 'abierta'
        CHECK (estado_gestion IN ('abierta', 'cerrada')),
    CHECK (fecha_final_g > fecha_inicio_g),
    CHECK (anio = EXTRACT(YEAR FROM fecha_inicio_g))
);

CREATE TABLE periodo (
    id_periodo            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_periodo        VARCHAR(50) NOT NULL,
    tipo                  VARCHAR(20)
        CHECK (tipo IN ('trimestre', 'bimestre', 'semestre')),
    fecha_inicio_p        DATE NOT NULL,
    fecha_final_p         DATE NOT NULL,
    estado_periodo        VARCHAR(20) NOT NULL DEFAULT 'abierto'
        CHECK (estado_periodo IN ('abierto', 'cerrado')),
    observaciones_periodo TEXT,
    id_gestion_periodo    INTEGER NOT NULL REFERENCES gestion(id_gestion),
    UNIQUE (id_gestion_periodo, nombre_periodo),
    CHECK (fecha_final_p > fecha_inicio_p)
);

CREATE TABLE curso (
    id_curso       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paralelo       VARCHAR(5) NOT NULL,
    cupo_maximo    INTEGER NOT NULL DEFAULT 35 CHECK (cupo_maximo > 0),
    id_grado_curso INTEGER NOT NULL REFERENCES grado(id_grado),
    UNIQUE (id_grado_curso, paralelo)
);

-- =====================================================================
-- 4. MATERIAS, PLAN DE ESTUDIOS, AULAS, ASIGNACIONES Y HORARIOS
-- =====================================================================

CREATE TABLE materia (
    id_materia     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_materia VARCHAR(100) NOT NULL UNIQUE,
    carga_horaria  INTEGER CHECK (carga_horaria > 0)
);

-- Plan de estudios: que materias corresponden a cada grado.
CREATE TABLE materia_grado (
    id_grado_mg   INTEGER NOT NULL REFERENCES grado(id_grado) ON DELETE CASCADE,
    id_materia_mg INTEGER NOT NULL REFERENCES materia(id_materia) ON DELETE CASCADE,
    PRIMARY KEY (id_grado_mg, id_materia_mg)
);

CREATE TABLE aula (
    id_aula     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero      VARCHAR(10) NOT NULL UNIQUE,
    capacidad   INTEGER CHECK (capacidad > 0),
    tipo_aula   VARCHAR(30),
    estado_aula VARCHAR(20) NOT NULL DEFAULT 'disponible'
        CHECK (estado_aula IN ('disponible', 'mantenimiento', 'inactiva'))
);

CREATE TABLE asignacion_profesor_clase (
    id_asignacion          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ci_profesor_asignacion VARCHAR(20) NOT NULL
        REFERENCES profesor(ci_profesor) ON UPDATE CASCADE,
    id_materia_asignacion  INTEGER NOT NULL REFERENCES materia(id_materia),
    id_curso_asignacion    INTEGER NOT NULL REFERENCES curso(id_curso),
    id_aula_asignacion     INTEGER NOT NULL REFERENCES aula(id_aula),
    id_gestion_asignacion  INTEGER NOT NULL REFERENCES gestion(id_gestion),
    creado_en              TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id_curso_asignacion, id_materia_asignacion, id_gestion_asignacion)
);

CREATE TABLE horario (
    id_horario            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia                   VARCHAR(10) NOT NULL
        CHECK (dia IN ('lunes','martes','miercoles','jueves','viernes','sabado','domingo')),
    hora_inicio_h         TIME NOT NULL,
    hora_final_f          TIME NOT NULL,
    id_asignacion_horario INTEGER NOT NULL
        REFERENCES asignacion_profesor_clase(id_asignacion) ON DELETE CASCADE,
    CHECK (hora_final_f > hora_inicio_h)
);

-- =====================================================================
-- 5. EVALUACION: DIMENSIONES, INSCRIPCIONES, ASISTENCIA, CALIFICACIONES
-- =====================================================================

-- Dimensiones de evaluacion por gestion (ser, saber, hacer, decidir,
-- autoevaluacion). La suma de puntaje_maximo de una gestion debe ser 100.
CREATE TABLE dimension_evaluacion (
    id_dimension         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_dimension     VARCHAR(30) NOT NULL,
    puntaje_maximo       NUMERIC(5,2) NOT NULL CHECK (puntaje_maximo > 0 AND puntaje_maximo <= 100),
    es_autoevaluacion    BOOLEAN NOT NULL DEFAULT false,
    orden_dimension      SMALLINT NOT NULL DEFAULT 1,
    id_gestion_dimension INTEGER NOT NULL REFERENCES gestion(id_gestion),
    UNIQUE (id_gestion_dimension, nombre_dimension)
);
-- Solo una dimension de autoevaluacion por gestion
CREATE UNIQUE INDEX uq_dimension_autoevaluacion
    ON dimension_evaluacion(id_gestion_dimension) WHERE es_autoevaluacion;

CREATE TABLE inscripcion (
    id_inscripcion            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inscripcion         DATE NOT NULL DEFAULT CURRENT_DATE,
    estado_inscripcion        VARCHAR(20) NOT NULL DEFAULT 'activa'
        CHECK (estado_inscripcion IN ('activa', 'retirada', 'finalizada')),
    fecha_retiro              DATE,
    motivo_retiro             TEXT,
    resultado_final           VARCHAR(20)
        CHECK (resultado_final IN ('promovido', 'reprobado')),
    ci_estudiante_inscripcion VARCHAR(20) NOT NULL
        REFERENCES estudiante(ci_estudiante) ON UPDATE CASCADE,
    id_gestion_inscripcion    INTEGER NOT NULL REFERENCES gestion(id_gestion),
    id_curso_inscripcion      INTEGER NOT NULL REFERENCES curso(id_curso),
    creado_en                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en            TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (ci_estudiante_inscripcion, id_gestion_inscripcion),
    CHECK ((estado_inscripcion = 'retirada') = (fecha_retiro IS NOT NULL)),
    CHECK (resultado_final IS NULL OR estado_inscripcion = 'finalizada')
);

CREATE TABLE asistencia (
    id_asistencia            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_asistencia         DATE NOT NULL DEFAULT CURRENT_DATE,
    estado_asistencia        VARCHAR(20) NOT NULL
        CHECK (estado_asistencia IN ('presente', 'ausente', 'tardanza', 'justificado')),
    observacion_asistencia   TEXT,
    id_asignacion_asistencia INTEGER NOT NULL REFERENCES asignacion_profesor_clase(id_asignacion),
    ci_estudiante_asistencia VARCHAR(20) NOT NULL
        REFERENCES estudiante(ci_estudiante) ON UPDATE CASCADE,
    UNIQUE (id_asignacion_asistencia, ci_estudiante_asistencia, fecha_asistencia)
);

-- Cabecera: una calificacion por estudiante, materia y periodo.
-- La gestion se obtiene del periodo (3FN) y la nota final se calcula
-- sumando calificacion_detalle (ver vista v_nota_final).
CREATE TABLE calificacion (
    id_calificacion            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_calificacion         DATE NOT NULL DEFAULT CURRENT_DATE,
    observacion_calificacion   TEXT,
    ci_estudiante_calificacion VARCHAR(20) NOT NULL
        REFERENCES estudiante(ci_estudiante) ON UPDATE CASCADE,
    id_materia_calificacion    INTEGER NOT NULL REFERENCES materia(id_materia),
    id_periodo_calificacion    INTEGER NOT NULL REFERENCES periodo(id_periodo),
    creado_en                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en             TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (ci_estudiante_calificacion, id_materia_calificacion, id_periodo_calificacion)
);

-- Detalle: puntaje obtenido en cada dimension.
CREATE TABLE calificacion_detalle (
    id_calificacion_detalle INTEGER NOT NULL
        REFERENCES calificacion(id_calificacion) ON DELETE CASCADE,
    id_dimension_detalle    INTEGER NOT NULL REFERENCES dimension_evaluacion(id_dimension),
    puntaje                 NUMERIC(5,2) NOT NULL CHECK (puntaje >= 0),
    PRIMARY KEY (id_calificacion_detalle, id_dimension_detalle)
);

-- =====================================================================
-- 6. BOLETINES Y LIBRETAS
-- =====================================================================

-- promedio_general_b es una "foto" del promedio al momento de emitir el
-- boletin (documento historico). El promedio vivo sale de v_nota_final.
CREATE TABLE boletin (
    id_boletin                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_emision_b                 DATE NOT NULL DEFAULT CURRENT_DATE,
    promedio_general_b              NUMERIC(5,2) CHECK (promedio_general_b BETWEEN 0 AND 100),
    observaciones_generales_boletin TEXT,
    id_periodo_boletin              INTEGER NOT NULL REFERENCES periodo(id_periodo),
    ci_estudiante_boletin           VARCHAR(20) NOT NULL
        REFERENCES estudiante(ci_estudiante) ON UPDATE CASCADE,
    UNIQUE (id_periodo_boletin, ci_estudiante_boletin)
);

CREATE TABLE libreta (
    id_libreta            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    archivo_digital_ruta  VARCHAR(255),
    fecha_emision_l       DATE NOT NULL DEFAULT CURRENT_DATE,
    ci_estudiante_libreta VARCHAR(20) NOT NULL
        REFERENCES estudiante(ci_estudiante) ON UPDATE CASCADE,
    id_gestion_libreta    INTEGER NOT NULL REFERENCES gestion(id_gestion),
    UNIQUE (ci_estudiante_libreta, id_gestion_libreta)
);
COMMENT ON COLUMN libreta.archivo_digital_ruta IS 'Ruta o URL del PDF de la libreta (el almacenamiento lo decide el backend, CU24).';

-- =====================================================================
-- 7. TUTORES, ARANCELES, BECAS Y PAGOS
-- =====================================================================

CREATE TABLE tutor_estudiante (
    ci_tutor_tutorestudiante      VARCHAR(20) NOT NULL
        REFERENCES tutor(ci_tutor) ON UPDATE CASCADE,
    ci_estudiante_tutorestudiante VARCHAR(20) NOT NULL
        REFERENCES estudiante(ci_estudiante) ON UPDATE CASCADE,
    parentesco          VARCHAR(30) NOT NULL,
    es_principal        BOOLEAN NOT NULL DEFAULT false,
    es_responsable_pago BOOLEAN NOT NULL DEFAULT false,
    autorizado_recoger  BOOLEAN NOT NULL DEFAULT true,
    PRIMARY KEY (ci_tutor_tutorestudiante, ci_estudiante_tutorestudiante),
    CHECK (ci_tutor_tutorestudiante <> ci_estudiante_tutorestudiante)
);
-- Un solo tutor principal por estudiante
CREATE UNIQUE INDEX uq_tutor_principal
    ON tutor_estudiante(ci_estudiante_tutorestudiante) WHERE es_principal;

-- Monto de la mensualidad por nivel y gestion
CREATE TABLE arancel (
    id_arancel         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monto_mensual      NUMERIC(10,2) NOT NULL CHECK (monto_mensual > 0),
    dia_vencimiento    SMALLINT NOT NULL DEFAULT 10 CHECK (dia_vencimiento BETWEEN 1 AND 28),
    id_gestion_arancel INTEGER NOT NULL REFERENCES gestion(id_gestion),
    id_nivel_arancel   INTEGER NOT NULL REFERENCES nivel_educativo(id_nivel),
    UNIQUE (id_gestion_arancel, id_nivel_arancel)
);

CREATE TABLE beca (
    id_beca              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    porcentaje_descuento NUMERIC(5,2) NOT NULL CHECK (porcentaje_descuento > 0 AND porcentaje_descuento <= 100),
    motivo_beca          VARCHAR(150),
    ci_estudiante_beca   VARCHAR(20) NOT NULL
        REFERENCES estudiante(ci_estudiante) ON UPDATE CASCADE,
    id_gestion_beca      INTEGER NOT NULL REFERENCES gestion(id_gestion),
    creado_en            TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (ci_estudiante_beca, id_gestion_beca)
);

CREATE SEQUENCE seq_numero_recibo START 1;

-- estado 'atrasado' ya no se guarda: es un dato que cambia con el tiempo
-- y se calcula en la vista v_estado_pagos (pendiente + vencido).
CREATE TABLE pago_mensualidad (
    id_pago                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mes                    SMALLINT NOT NULL CHECK (mes BETWEEN 1 AND 12),
    monto                  NUMERIC(10,2) NOT NULL CHECK (monto > 0),
    descuento_aplicado     NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (descuento_aplicado >= 0),
    fecha_vencimiento      DATE NOT NULL,
    fecha_pago             DATE,
    metodo_pago            VARCHAR(30)
        CHECK (metodo_pago IN ('efectivo', 'transferencia', 'qr', 'tarjeta')),
    estado_pago            VARCHAR(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado_pago IN ('pendiente', 'pagado', 'anulado')),
    numero_recibo          INTEGER UNIQUE,
    observacion_pago       TEXT,
    ci_administrativo_pago VARCHAR(20)
        REFERENCES administrativo(ci_administrativo) ON UPDATE CASCADE,
    ci_estudiante_pago     VARCHAR(20) NOT NULL
        REFERENCES estudiante(ci_estudiante) ON UPDATE CASCADE,
    ci_tutor_pago          VARCHAR(20),
    id_gestion_pago        INTEGER NOT NULL REFERENCES gestion(id_gestion),
    creado_en              TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en         TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (ci_estudiante_pago, id_gestion_pago, mes),
    -- el tutor que paga debe ser tutor de ESE estudiante
    FOREIGN KEY (ci_tutor_pago, ci_estudiante_pago)
        REFERENCES tutor_estudiante(ci_tutor_tutorestudiante, ci_estudiante_tutorestudiante)
        ON UPDATE CASCADE,
    -- un pago cobrado debe tener fecha, recibo, cajero y metodo
    CHECK (estado_pago <> 'pagado' OR (fecha_pago IS NOT NULL AND numero_recibo IS NOT NULL
                                       AND ci_administrativo_pago IS NOT NULL AND metodo_pago IS NOT NULL)),
    CHECK (estado_pago <> 'pendiente' OR (fecha_pago IS NULL AND numero_recibo IS NULL))
);

-- =====================================================================
-- 8. INVENTARIO
-- =====================================================================

-- cantidad_inventario la mantiene un trigger a partir de los movimientos
-- (redundancia controlada: el backend no la edita directamente; el
--  CHECK >= 0 impide que un movimiento deje el stock en negativo).
CREATE TABLE inventario (
    id_inventario          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_inventario      VARCHAR(100) NOT NULL UNIQUE,
    cantidad_inventario    INTEGER NOT NULL DEFAULT 0 CHECK (cantidad_inventario >= 0),
    observacion_inventario TEXT,
    creado_en              TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE movimiento_inventario (
    id_movimiento                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_acceso_inventario      TIMESTAMPTZ NOT NULL DEFAULT now(),
    tipo_accion_inventario       VARCHAR(20) NOT NULL
        CHECK (tipo_accion_inventario IN ('entrada', 'salida')),
    cantidad_movimiento          INTEGER NOT NULL CHECK (cantidad_movimiento > 0),
    motivo_movimiento            TEXT,
    destino_movimiento           VARCHAR(100),
    ci_administrativo_movimiento VARCHAR(20) NOT NULL
        REFERENCES administrativo(ci_administrativo) ON UPDATE CASCADE,
    id_inventario_movimiento     INTEGER NOT NULL REFERENCES inventario(id_inventario)
);

-- =====================================================================
-- 9. SEGUIMIENTO Y COMUNICADOS
-- =====================================================================

CREATE TABLE seguimiento_estudiante (
    id_seguimiento            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_seguimiento         DATE NOT NULL DEFAULT CURRENT_DATE,
    tipo_seguimiento          VARCHAR(20) NOT NULL
        CHECK (tipo_seguimiento IN ('conducta', 'academico', 'salud', 'merito', 'otro')),
    gravedad                  VARCHAR(20)
        CHECK (gravedad IN ('leve', 'grave', 'muy_grave')),
    descripcion_seguimiento   TEXT NOT NULL,
    accion_tomada             TEXT,
    ci_estudiante_seguimiento VARCHAR(20) NOT NULL
        REFERENCES estudiante(ci_estudiante) ON UPDATE CASCADE,
    ci_registrado_por         VARCHAR(20) NOT NULL
        REFERENCES persona(ci) ON UPDATE CASCADE,
    creado_en                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (gravedad IS NULL OR tipo_seguimiento = 'conducta')
);

CREATE TABLE comunicado (
    id_comunicado            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo                   VARCHAR(150) NOT NULL,
    contenido                TEXT NOT NULL,
    tipo_comunicado          VARCHAR(20) NOT NULL DEFAULT 'general'
        CHECK (tipo_comunicado IN ('general', 'citacion')),
    alcance                  VARCHAR(20) NOT NULL
        CHECK (alcance IN ('todos', 'curso', 'estudiante')),
    fecha_publicacion        TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_citacion           TIMESTAMPTZ,
    id_gestion_comunicado    INTEGER NOT NULL REFERENCES gestion(id_gestion),
    id_curso_comunicado      INTEGER REFERENCES curso(id_curso),
    ci_estudiante_comunicado VARCHAR(20)
        REFERENCES estudiante(ci_estudiante) ON UPDATE CASCADE,
    ci_autor                 VARCHAR(20) NOT NULL
        REFERENCES persona(ci) ON UPDATE CASCADE,
    creado_en                TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- el destinatario debe coincidir con el alcance
    CHECK (
        (alcance = 'todos'      AND id_curso_comunicado IS NULL     AND ci_estudiante_comunicado IS NULL) OR
        (alcance = 'curso'      AND id_curso_comunicado IS NOT NULL AND ci_estudiante_comunicado IS NULL) OR
        (alcance = 'estudiante' AND id_curso_comunicado IS NULL     AND ci_estudiante_comunicado IS NOT NULL)
    ),
    -- una citacion es siempre para un estudiante (sus tutores) y tiene fecha
    CHECK ((tipo_comunicado = 'citacion') = (fecha_citacion IS NOT NULL)),
    CHECK (tipo_comunicado <> 'citacion' OR alcance = 'estudiante')
);

CREATE TABLE comunicado_lectura (
    id_comunicado_lectura INTEGER NOT NULL
        REFERENCES comunicado(id_comunicado) ON DELETE CASCADE,
    ci_persona_lectura    VARCHAR(20) NOT NULL
        REFERENCES persona(ci) ON UPDATE CASCADE,
    leido_en              TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (id_comunicado_lectura, ci_persona_lectura)
);

-- =====================================================================
